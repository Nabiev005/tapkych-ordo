async function main() {
  const force = process.argv.includes('--force');
  const count = await prisma.question.count();
  if (count > 0 && !force) {
    console.log(`Базада ${count} суроо бар — seed өткөрүлүп жиберилди. Кайра жүктөө үчүн: npm run db:seed -- --force`);
    return;
  }
  if (force) await prisma.question.deleteMany();

  const sets = [
    ['ROUND1', ROUND1],
    ['ROUND2', ROUND2],
    ['FINAL', FINAL],
  ] as const;

  for (const [round, list] of sets) {
    await prisma.question.createMany({
      data: list.map(([text, optionA, optionB, optionC, optionD, correct], order) => ({
        round,
        order,
        text,
        optionA,
        optionB,
        optionC,
        optionD,
        correct,
      })),
    });
  }
  console.log('✓ 25 мисал суроо кошулду (1-тур: 10, 2-тур: 10, финал: 5)');
}

main()
